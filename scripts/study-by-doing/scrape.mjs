#!/usr/bin/env node
/**
 * ai.studybydoing.in — curriculum extractor + personal offline mirror.
 *
 * Two jobs, both opt-in:
 *
 *   1. Always: read the course sidebar (`<nav class="side">`) from the home
 *      page and write the full curriculum index (sections -> lessons) to
 *      frontend/src/data/studyByDoingData.js. This powers the in-app
 *      "Study By Doing" hub page.
 *
 *   2. Only with `--mirror`: download every page in sitemap.xml plus the shared
 *      course assets into .mirror/ so you can read the course offline. That
 *      folder is git-ignored and never shipped with the app.
 *
 * Usage:
 *   node scripts/study-by-doing/scrape.mjs            # refresh catalog only
 *   node scripts/study-by-doing/scrape.mjs --mirror   # catalog + offline copy
 */
import { writeFile, mkdir, readFile } from 'node:fs/promises'
import { existsSync } from 'node:fs'
import path from 'node:path'

const ORIGIN = 'https://ai.studybydoing.in'
const ROOT = path.resolve(new URL('../../', import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, '$1'))
const DATA_FILE = path.join(ROOT, 'frontend', 'src', 'data', 'studyByDoingData.js')
const MIRROR_DIR = path.join(ROOT, '.mirror')
const MIRROR = process.argv.includes('--mirror')

const UA = 'Mozilla/5.0 (compatible; study-by-doing-personal-mirror/1.0)'
const CONCURRENCY = 6

async function get(url) {
  const res = await fetch(url.startsWith('http') ? url : ORIGIN + url, { headers: { 'user-agent': UA } })
  if (!res.ok) throw new Error(`${res.status} ${url}`)
  return res.text()
}

const decode = s =>
  s
    .replace(/&amp;/g, '&')
    .replace(/&lt;/g, '<')
    .replace(/&gt;/g, '>')
    .replace(/&quot;/g, '"')
    .replace(/&#39;|&apos;/g, "'")
    .replace(/&nbsp;/g, ' ')
    .replace(/\s+/g, ' ')
    .trim()

const strip = s => decode(s.replace(/<[^>]*>/g, ' '))

/* ── 1. Parse the course sidebar into sections ─────────────────────── */

function parseSidebar(html) {
  const nav = html.match(/<nav class="side"[\s\S]*?<\/nav>/)
  if (!nav) throw new Error('Could not find <nav class="side"> on the home page')

  const sections = []
  const loose = []

  // Walk the nav sequentially: a `div.part` opens a section whose lessons are
  // the <li> entries up to the next `div.part`.
  const tokenRe = /<div class="part">([\s\S]*?)<\/div>|<li>\s*<a href="([^"]+)"[^>]*>([\s\S]*?)<\/a>\s*<\/li>|<a class="home[^"]*"[^>]*href="([^"]+)"[^>]*>([\s\S]*?)<\/a>/g
  let m
  let current = null

  while ((m = tokenRe.exec(nav[0])) !== null) {
    if (m[1] !== undefined) {
      const raw = decode(m[1])
      const gi = (raw.match(/class="gi">([^<]*)</) || [, ''])[1]
      const title = strip(m[1].replace(/<span class="gi">[\s\S]*?<\/span>/, ''))
      current = { icon: gi.trim(), title, lessons: [] }
      sections.push(current)
    } else if (m[2] !== undefined) {
      const label = strip(m[3])
      const num = (m[3].match(/class="n">([^<]*)</) || [, ''])[1].trim()
      const title = strip(m[3].replace(/<span class="n">[\s\S]*?<\/span>/, ''))
      const lesson = { n: num, title: title || label, slug: m[2].replace(/^\/+/, '') }
      if (current) current.lessons.push(lesson)
      else loose.push(lesson)
    } else if (m[4] !== undefined) {
      const href = m[4].replace(/^\/+/, '')
      if (!href) continue
      loose.push({ n: '★', title: strip(m[5]), slug: href })
    }
  }

  return { sections: sections.filter(s => s.lessons.length), loose }
}

/* ── 2. Write the app data module ──────────────────────────────────── */

async function writeCatalog(sections, loose, totalUrls) {
  const sectionsJs = sections
    .map(s => {
      const lessons = s.lessons
        .map(l => `      { n: ${JSON.stringify(l.n)}, title: ${JSON.stringify(l.title)}, slug: ${JSON.stringify(l.slug)} },`)
        .join('\n')
      return `  {
    id: ${JSON.stringify(slugify(s.title))},
    icon: ${JSON.stringify(s.icon)},
    title: ${JSON.stringify(s.title)},
    lessons: [
${lessons}
    ],
  },`
    })
    .join('\n')

  const looseJs = loose
    .map(l => `  { n: ${JSON.stringify(l.n)}, title: ${JSON.stringify(l.title)}, slug: ${JSON.stringify(l.slug)} },`)
    .join('\n')

  const lessonCount = sections.reduce((a, s) => a + s.lessons.length, 0) + loose.length

  const out = `// GENERATED by scripts/study-by-doing/scrape.mjs — do not edit by hand.
// Curriculum index for the ai.studybydoing.in course. Only navigation metadata
// (section names, lesson numbers, lesson titles and URLs) is stored here; the
// lesson content itself stays on the source site.

export const SBD_ORIGIN = ${JSON.stringify(ORIGIN)}

export const SBD_SECTIONS = [
${sectionsJs}
]

/** Top-level links that sit above the numbered groups in the course sidebar. */
export const SBD_LOOSE_LINKS = [
${looseJs}
]

export const SBD_TOTAL_PAGES = ${totalUrls}
export const SBD_TOTAL_LESSONS = ${lessonCount}
`

  await mkdir(path.dirname(DATA_FILE), { recursive: true })
  await writeFile(DATA_FILE, out)
  console.log(`catalog  -> ${path.relative(ROOT, DATA_FILE)}`)
  console.log(`           ${sections.length} sections, ${lessonCount} lessons, ${totalUrls} sitemap pages`)
}

function slugify(s) {
  return s.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '')
}

/* ── 3. Optional offline mirror ────────────────────────────────────── */

async function mirror(sitemapXml) {
  const urls = [...sitemapXml.matchAll(/<loc>([^<]+)<\/loc>/g)].map(m => m[1])
  await mkdir(MIRROR_DIR, { recursive: true })
  console.log(`mirror   -> ${path.relative(ROOT, MIRROR_DIR)}  (${urls.length} pages)`)

  const queue = [...urls]
  let done = 0
  let failed = 0

  async function worker() {
    while (queue.length) {
      const url = queue.shift()
      const rel = url.replace(ORIGIN, '').replace(/^\/+/, '') || 'index'
      try {
        const html = await get(url)
        const file = path.join(MIRROR_DIR, rel.endsWith('.html') ? rel : `${rel}.html`)
        await mkdir(path.dirname(file), { recursive: true })
        await writeFile(file, html)
        done++
      } catch (err) {
        failed++
        console.warn(`           ! ${url} — ${err.message}`)
      }
      if ((done + failed) % 25 === 0) process.stdout.write(`\r           ${done + failed}/${urls.length} fetched`)
    }
  }

  // Shared assets used by every page.
  for (const asset of ['assets/course.css?v=44', 'assets/nav.js?v=29', 'assets/protect.js?v=1', 'assets/copybtn.js?v=2', 'assets/svgfit.js?v=1']) {
    try {
      const body = await get('/' + asset)
      const file = path.join(MIRROR_DIR, asset.split('?')[0])
      await mkdir(path.dirname(file), { recursive: true })
      await writeFile(file, body)
    } catch { /* non-fatal */ }
  }

  await Promise.all(Array.from({ length: CONCURRENCY }, worker))
  process.stdout.write('\n')
  console.log(`           ${done} pages saved, ${failed} failed`)
}

/* ── main ──────────────────────────────────────────────────────────── */

const sitemapXml = existsSync(path.join(ROOT, '.scratch', 'sitemap.xml'))
  ? await readFile(path.join(ROOT, '.scratch', 'sitemap.xml'), 'utf8')
  : await get('/sitemap.xml')

const totalUrls = [...sitemapXml.matchAll(/<loc>([^<]+)<\/loc>/g)].length

const homeHtml = await get('/')
const { sections, loose } = parseSidebar(homeHtml)
await writeCatalog(sections, loose, totalUrls)

if (MIRROR) await mirror(sitemapXml)
