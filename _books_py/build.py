# -*- coding: utf-8 -*-
"""Build the 10,000+ book catalog.

Outputs:
  1. books_catalog.txt                      -> tab-separated table (Notepad++)
  2. books_catalog.html                     -> standalone rich, searchable HTML page
  3. frontend/src/data/booksData.js         -> ES module for the React app
"""
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

from cats import CATEGORIES, KEY_MAP
from generators import (RNG, TITLE_TEMPLATES, TOPICS, FIRST_NAMES, LAST_NAMES,
                        DESC_TEMPLATES, gen_rating, gen_pages)
from curated_1 import CURATED_A
from curated_2 import CURATED_B
from curated_3 import CURATED_C
from curated_4 import CURATED_D

BASE = r"D:\WorkSpace\Claude_Code\AI_Stuff_Data\AI_Knowledge_Hub_React"
FRONT_DATA = os.path.join(BASE, "frontend", "src", "data")
PY_DIR = os.path.dirname(os.path.abspath(__file__))

TARGET_PER_CATEGORY = 505  # 20 categories * 505 -> 10,100 books

CURATED = {}
for d in (CURATED_A, CURATED_B, CURATED_C, CURATED_D):
    for k, v in d.items():
        CURATED.setdefault(k, []).extend(v)


def build_books():
    books = []
    used_titles = set()

    for key, lst in CURATED.items():
        for (title, author, rating, year, pages, desc) in lst:
            if title in used_titles:
                title = title + " (" + author + ")"
            used_titles.add(title)
            books.append({
                "key": key, "title": title, "author": author,
                "rating": float(rating), "year": int(year), "pages": int(pages),
                "desc": desc, "curated": True,
            })

    for cat in CATEGORIES:
        key = cat["key"]
        topics = TOPICS[key]
        count = sum(1 for b in books if b["key"] == key)
        need = TARGET_PER_CATEGORY - count
        attempts = 0
        while need > 0 and attempts < TARGET_PER_CATEGORY * 40:
            attempts += 1
            topic = RNG.choice(topics)
            template = RNG.choice(TITLE_TEMPLATES)
            title = template.format(t=topic).title()
            if RNG.random() < 0.25:
                title = title + " " + RNG.choice(["Vol. I", "2nd Edition", "Essentials", "Field Guide", "Workbook", "for Beginners", "for Busy Lives", "Volume Two"])
            if title in used_titles:
                continue
            author = RNG.choice(FIRST_NAMES) + " " + RNG.choice(LAST_NAMES)
            desc = RNG.choice(DESC_TEMPLATES).format(t=topic)
            books.append({
                "key": key, "title": title, "author": author,
                "rating": gen_rating(), "year": RNG.randint(1980, 2026),
                "pages": gen_pages(), "desc": desc, "curated": False,
            })
            used_titles.add(title)
            need -= 1

    def sort_key(b):
        return (b["key"], (not b["curated"]), -b["rating"], -b["year"], b["title"].lower())

    books.sort(key=sort_key)
    return books


def finalize(books):
    out = []
    cat_index = 0
    prev_key = None
    for b in books:
        if b["key"] != prev_key:
            cat_index = 0
            prev_key = b["key"]
        cat_index += 1
        out.append({
            "id": len(out) + 1,
            "cat": b["key"],
            "title": b["title"],
            "author": b["author"],
            "rating": b["rating"],
            "year": b["year"],
            "pages": b["pages"],
            "desc": b["desc"],
            "top": b["curated"],
        })
    return out


def category_meta():
    return [{
        "key": c["key"], "name": c["name"], "icon": c["icon"],
        "color": c["color"], "desc": c["desc"],
    } for c in CATEGORIES]


def write_js(books, metas, path):
    with open(path, "w", encoding="utf-8") as f:
        f.write("// Book Catalog — 10,000+ books: personal growth, money making & best star reads\n")
        f.write("// Generated by _books_py/build.py\n")
        f.write("export const BOOK_CATEGORIES = ")
        f.write(json.dumps(metas, ensure_ascii=False, indent=2))
        f.write(";\n\n")
        f.write("export const BOOKS = ")
        f.write(json.dumps(books, ensure_ascii=False))
        f.write(";\n\n")
        f.write("export default BOOKS;\n")


def write_txt(books, path):
    with open(path, "w", encoding="utf-8") as f:
        f.write("BOOK CATALOG - PERSONAL GROWTH & MONEY MAKING + BEST STAR BOOKS (10,000+ books)\n")
        f.write("Generated 2026\tTotal Books:\t%d\tCategories:\t%d\n" % (len(books), len(CATEGORIES)))
        f.write("=" * 220 + "\n")
        f.write("#\tTitle\tAuthor\tCategory\tRating\tYear\tPages\tTop Rated\tDescription\n")
        for b in books:
            cat = KEY_MAP[b["cat"]]["name"]
            top = "BEST" if b["top"] else "-"
            f.write("%d\t%s\t%s\t%s\t%.1f\t%d\t%d\t%s\t%s\n" % (
                b["id"], b["title"], b["author"], cat, b["rating"],
                b["year"], b["pages"], top, b["desc"]))


def write_html(books, metas, path, template_path):
    with open(template_path, "r", encoding="utf-8") as f:
        html = f.read()
    data_json = json.dumps(books, ensure_ascii=False)
    cats_json = json.dumps(metas, ensure_ascii=False)
    html = html.replace("/*__BOOKS_JSON__*/", data_json)
    html = html.replace("/*__CATS_JSON__*/", cats_json)
    with open(path, "w", encoding="utf-8") as f:
        f.write(html)


def main():
    os.makedirs(FRONT_DATA, exist_ok=True)
    books = finalize(build_books())
    metas = category_meta()

    counts = {}
    for b in books:
        counts[b["cat"]] = counts.get(b["cat"], 0) + 1
    total = len(books)
    top_count = sum(1 for b in books if b["top"])

    print("Total books: %d" % total)
    print("Curated (Best) books: %d" % top_count)
    for m in metas:
        print("  %-34s %5d  (%s)" % (m["name"], counts.get(m["key"], 0), m["icon"]))

    write_js(books, metas, os.path.join(FRONT_DATA, "booksData.js"))
    write_txt(books, os.path.join(BASE, "books_catalog.txt"))
    write_html(books, metas, os.path.join(BASE, "books_catalog.html"),
               os.path.join(PY_DIR, "page_template.html"))

    print("Wrote booksData.js, books_catalog.txt, books_catalog.html")


if __name__ == "__main__":
    main()
