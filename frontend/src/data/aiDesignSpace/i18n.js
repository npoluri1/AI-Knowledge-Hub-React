export const STRINGS = { en: EN, es: ES, fr: FR, de: DE, hi: HI, zh: ZH, pt: PT, ar: AR }

export const translate = (lang, key, vars) => {
  let s = (STRINGS[lang] && STRINGS[lang][key]) ?? EN[key] ?? key
  if (vars) Object.entries(vars).forEach(([k, v]) => { s = s.replace(new RegExp(`\\{${k}\\}`, 'g'), v) })
  return s
}
